"""Write db/schema.sql — the MySQL 8 / TiDB DDL generated from the SQLAlchemy models
(the app creates these tables itself; this file documents them for the report)."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sqlalchemy.dialects import mysql
from sqlalchemy.schema import CreateIndex, CreateTable

from debtlens.api.models import Base

ROOT = Path(__file__).resolve().parents[1]

parts = ["-- DebtLens v2 schema (MySQL 8 / TiDB).  Generated by scripts/export_schema.py — do not edit by hand.",
         "-- Demo-1 tables keep their names: user, project, module, assignment, technical_debt, incident, root_cause, resolution.",
         "SET NAMES utf8mb4;", ""]
for t in Base.metadata.sorted_tables:
    parts.append(str(CreateTable(t).compile(dialect=mysql.dialect())).strip() + ";")
    for ix in sorted(t.indexes, key=lambda i: i.name or ""):
        parts.append(str(CreateIndex(ix).compile(dialect=mysql.dialect())).strip() + ";")
    parts.append("")
(ROOT / "db" / "schema.sql").write_text("\n".join(parts), encoding="utf-8")
print(f"wrote db/schema.sql ({len(Base.metadata.sorted_tables)} tables)")
